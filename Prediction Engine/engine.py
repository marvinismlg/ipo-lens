# Meant to score the similarity of other stocks to SpaceX using a mathematical engine, as well as built-in python averaging and mathematical functions
# Essentially, the function takes a parameter, loops through the various company Financial Data and metadata to be compared (comparison_data) picks si specific metrics, and compares the metrics of the chosen profile, to the SpaceX profile we defined earlier

def scoring_function(comparison_data):
    scored_tranches = []
    primary_metrics = ["momentum", "volatility", "unlock_to_volume", "market_cap", "price_to_sales", "revenue_growth"]
    fallback_metrics = ["momentum", "volatility", "unlock_to_volume", "market_cap"]
    for data in comparison_data:
        primary_valid = all(
            data[metric][0] is not None and data[metric][1] is not None
            for metric in primary_metrics)
        if primary_valid:
            metrics = primary_metrics
        else:
            fallback_valid = all(
                data[metric][0] is not None and data[metric][1] is not None
                for metric in fallback_metrics)
            if not fallback_valid:
                error_logging("invalid_comparison")
                print("Invalid comparison value, skipping...")
                continue
            metrics = fallback_metrics
        metric_scores = []
        for metric in metrics:
            spacex_value, historical_value = data[metric]
            difference = abs(historical_value - spacex_value)
            scale = (abs(spacex_value) + abs(historical_value)) / 2
            if scale == 0:
                metric_similarity = 1.0
            else:
                normalized_difference = difference / scale
                metric_similarity = 1 / (1 + normalized_difference)
            metric_scores.append(metric_similarity)
        overall_score = sum(metric_scores) / len(metric_scores)
        scored_record = {
            "spacex_tranche": data["spacex_tranche"],
            "historical_ticker": data["historical_ticker"],
            "historical_tranche": data["historical_tranche"],
            "historical_return": data.get("historical_return"),
            "similarity_score": overall_score}
        scored_tranches.append(scored_record)
    return scored_tranches
# This is the pseudo prediction model that actually tells us if the stock is bearish or bullish, I'll likely simply do this using a Bool value, if the function returns False, I'll have an if statement that decides its "Bearish", if the function returns True, I'll have an if statement that decides its "Bullish"
# DISCLAIMER: THIS IS A PSEUDO PREDICTION ALGORITHM. THIS ENGINE IS MEANT SOLELY FOR THE PURPOSE OF DEMONSTRATING TECHNICAL DEPTH AND SHOULD NOT BE USED TO EVALUATE REAL FINANCIAL RISK OR MAKE INVESTMENT DECISIONS

def prediction_function(SPACEX_PROFILE, finished_profiles):
    bullish_evidence = 0
    bearish_evidence = 0
    primary_metrics = ["momentum", "volatility", "unlock_to_volume", "market_cap", "price_to_sales", "revenue_growth"]
    fallback_metrics = ["momentum", "volatility", "unlock_to_volume", "market_cap"]
    for profile in finished_profiles:
        historical_outcome = profile["historical_return"]
        if historical_outcome is None:
            error_logging("empty_historical_outcome")
            print("Empty historical return, cannot run prediction function on this specific value")
            continue
        predictive_influences = []
        for spacex_profile in SPACEX_PROFILE:
            primary_valid = all(
                spacex_profile[metric] is not None and profile[metric] is not None
                for metric in primary_metrics)
            if primary_valid:
                metrics = primary_metrics
            else:
                fallback_valid = all(
                    spacex_profile[metric] is not None and profile[metric] is not None
                    for metric in fallback_metrics)
                if not fallback_valid:
                    continue
                metrics = fallback_metrics
            spacex_distances = []
            for metric in metrics:
                spacex_value = spacex_profile[metric]
                historical_value = profile[metric]
                difference = abs(historical_value - spacex_value)
                scale = (abs(spacex_value) + abs(historical_value)) / 2
                if scale == 0:
                    normalized_distance = 0.0
                else:
                    normalized_distance = difference / scale
                spacex_distances.append(normalized_distance)
            average_distance = sum(spacex_distances) / len(spacex_distances)
            influence_weight = 1 / (1 + average_distance)
            predictive_influences.append(influence_weight)
        if not predictive_influences:
            continue
        combined_influence = sum(predictive_influences) / len(predictive_influences)
        if historical_outcome > 0:
            bullish_evidence += combined_influence
        elif historical_outcome < 0:
            bearish_evidence += combined_influence
    total_evidence = bullish_evidence + bearish_evidence
    if total_evidence == 0:
        return {
            "bullish_percentage": None,
            "bearish_percentage": None,
            "prediction": "Insufficient Data"}
    bullish_percentage = (bullish_evidence / total_evidence) * 100
    bearish_percentage = (bearish_evidence / total_evidence) * 100
    if bullish_percentage > bearish_percentage:
        prediction = "Bullish"
    elif bearish_percentage > bullish_percentage:
        prediction = "Bearish"
    else:
        prediction = "Mixed"
    forecast = {
        "bullish_percentage": bullish_percentage,
        "bearish_percentage": bearish_percentage,
        "prediction": prediction}
    return forecast

