def thirty_day_momentum(date_windows):
    momentum_results = []
    for window_record in date_windows:
        trading_window = window_record["trading_window"]
        first_close = float(trading_window[0]["close"])
        last_close = float(trading_window[-1]["close"])
        momentum = (last_close / first_close) - 1
        momentum_results.append(momentum)
    return momentum_results

