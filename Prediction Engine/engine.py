# Error logging helper function, intakes the dictionary key an adds the errors to error_logs.csv
def error_logging(error_key):
    if error_key not in errors: # Conditional to check the valid key exists.
        return
    with open(Error_Logs, 'a') as csvfile:
        append = csv.writer(csvfile)
        timestamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
        error_dict = errors[error_key]

        var1 = error_dict["Function Name"]
        var2 = error_dict["Error Type"]
        var3 = error_dict["Message"]
        var4 = error_dict["Severity"]

        append.writerow([timestamp, var1, var2, var3, var4])


