# The question we are trying to answer is "What happened to the stock after its original lockup expiration?"

def historical_return(date_window, filtered_companies):
    historical_results = []

    sorted_companies = sorted(
        filtered_companies,
        key=lambda company: datetime.datetime.strptime(company["date"], "%Y-%m-%d"))
    for window_record in date_window:
        lockup_date = window_record["lockup"]["lockup_date"]
        lockup_datetime = datetime.datetime.strptime(lockup_date, "%Y-%m-%d")
        post_lockup_rows = []
        for company in sorted_companies:
            company_datetime = datetime.datetime.strptime(company["date"], "%Y-%m-%d")
            if company_datetime >= lockup_datetime:
                post_lockup_rows.append(company)
        if len(post_lockup_rows) >= 21:
            starting_close = float(post_lockup_rows[0]["close"])
            ending_close = float(post_lockup_rows[20]["close"])

            twenty_day_return = (ending_close / starting_close) - 1
            historical_results.append(twenty_day_return)
        else:
            historical_results.append(None)
    return historical_results

def market_cap_metric(date_window):
    market_cap_results = []
    for window_record in date_window:
        trading_window = window_record["trading_window"]
        latest_market_cap = None
        for company in reversed(trading_window):
            if company["market_cap"]:
                latest_market_cap = float(company["market_cap"])
                break
        market_cap_results.append(latest_market_cap)
    return market_cap_results


def price_to_sales(date_window):
    price_to_sales_results = []
    for window_record in date_window:
        trading_window = window_record["trading_window"]
        price_to_sales_ratio = None
        for company in reversed(trading_window):
            if company["market_cap"] and company["revenue"] and company["period"] == "TTM":
                market_cap = float(company["market_cap"])
                ttm_revenue = float(company["revenue"])

                if ttm_revenue != 0:
                    price_to_sales_ratio = market_cap / ttm_revenue
                    break
        price_to_sales_results.append(price_to_sales_ratio)
    return price_to_sales_results

# Function for calculating the company's revenue growth

def revenue_growth(date_window, filtered_companies):
    revenue_growth_results = []
    sorted_companies = sorted(
        filtered_companies,
        key=lambda company: datetime.datetime.strptime(company["date"], "%Y-%m-%d"))
    for window_record in date_window:
        lockup_date = window_record["lockup"]["lockup_date"]
        lockup_datetime = datetime.datetime.strptime(lockup_date, "%Y-%m-%d")
        revenue_updates = []
        previous_revenue = None
        for company in sorted_companies:
            company_datetime = datetime.datetime.strptime(company["date"], "%Y-%m-%d")
            if company_datetime >= lockup_datetime:
                break
            if company["revenue"] and company["period"] == "TTM":
                current_revenue = float(company["revenue"])
                if current_revenue != previous_revenue:
                    revenue_updates.append(current_revenue)
                    previous_revenue = current_revenue
        if len(revenue_updates) >= 5:
            current_ttm_revenue = revenue_updates[-1]
            prior_year_ttm_revenue = revenue_updates[-5]
            if prior_year_ttm_revenue != 0:
                growth = (current_ttm_revenue / prior_year_ttm_revenue) - 1
                revenue_growth_results.append(growth)
            else:
                revenue_growth_results.append(None)
        else:
            revenue_growth_results.append(None)
    return revenue_growth_results

