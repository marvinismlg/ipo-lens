def volatility(date_window):
    volatility_results = []
    for window_record in date_window:
        trading_window = window_record["trading_window"]
        daily_returns = []
        for day_index in range(1, len(trading_window)): # This inner loop is meant to find the exact day-to-day close and previous close. We cannot use basic indexing because volatility needs to compare everything to the day before it
            current_close = float(trading_window[day_index]["close"])
            previous_close = float(trading_window[day_index - 1]["close"])

            daily_return_calculation = current_close / previous_close - 1

            daily_returns.append(daily_return_calculation)
        # End of the inner loop, the purpose was to simply calculate the daily return percentage and add it to daily_returns for each company
        if len(daily_returns) < 2:
            error_logging("volatility_chart")
            raise ValueError("Volatility cannot be calculated with less than 2 entries")

        standard_deviation_volatility = statistics.stdev(daily_returns)
        volatility_results.append(standard_deviation_volatility)

    save_volatility_chart(date_window, volatility_results)
    return volatility_results

# This next function is meant to find the daily trading volume for each stock and tranche. This function allows us to calculate shares unlock with average trading volume, allowing us to see how much the shares unlocked affects the trading volume
def average_trading_volume(date_window):
    trading_volume_results = []
    for window_record in date_window:
        trading_window = window_record["trading_window"]
        daily_volume = []
        for day_index in range(0, len(trading_window)): # Inner loop is meant to iterate to each individual company day and return the day-to-day results from companies.csv
            day_volume = float(trading_window[day_index]["volume"])
            daily_volume.append(day_volume)
        average_daily_volume = statistics.mean(daily_volume)
        trading_volume_results.append(average_daily_volume)
    return trading_volume_results

# A usable variable that allows us to access the output from average trading volume

def unlock_to_volume_ratio(date_window, avg_volume):
    ratio_results = []
    for index, window_record in enumerate(date_window):
        # Metadata uses millions; Yahoo volume uses individual shares.
        shares_unlocked = (
                float(window_record["lockup"]["shares_unlocked"]) * 1_000_000
        )
        matching_average_volume = avg_volume[index]
        if matching_average_volume == 0:
            ratio_results.append(None)
            continue
        u_to_v_ratio = shares_unlocked / matching_average_volume
        ratio_results.append(u_to_v_ratio)
    return ratio_results

