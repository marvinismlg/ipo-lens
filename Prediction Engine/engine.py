def engine_controller(selected_ticker):
    global companies, lockups, SPACEX_PROFILE, universe # Defines everything we had used before as global in this function, so we don't have undefined variables in the codebase when we move it

    companies = read_companies()
    lockups = read_ipo_lockups()

    spacex_companies_filter = company_filter("SPCX", companies)
    spacex_lockup_filter = lockup_filter("SPCX", lockups)
    spacex_date_window = date_window(spacex_lockup_filter, spacex_companies_filter)

    spacex_avg_volume = average_trading_volume(spacex_date_window)
    spacex_momentum = thirty_day_momentum(spacex_date_window)
    spacex_volatility = volatility(spacex_date_window)
    spacex_ratio = unlock_to_volume_ratio(spacex_date_window, spacex_avg_volume)
    spacex_market_cap = market_cap_metric(spacex_date_window)
    spacex_price_to_sales = price_to_sales(spacex_date_window)
    spacex_revenue_growth = revenue_growth(spacex_date_window, spacex_companies_filter)

    SPACEX_PROFILE = []
    for index, window in enumerate(spacex_date_window):
        spacex_profile = {
            "ticker": "SPCX",
            "tranche": window["lockup"]["tranche"],
            "momentum": spacex_momentum[index],
            "volatility": spacex_volatility[index],
            "unlock_to_volume": spacex_ratio[index],
            "market_cap": spacex_market_cap[index],
            "price_to_sales": spacex_price_to_sales[index],
            "revenue_growth": spacex_revenue_growth[index]
        }
        SPACEX_PROFILE.append(spacex_profile)

    historical_universe_return = prediction_historical_universe(universal_tickers)
    universe = prediction_function(SPACEX_PROFILE, historical_universe_return)

    return user_interface_controller(selected_ticker)
